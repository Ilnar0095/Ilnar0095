def main_product(topic: str) -> str:
    words = [w for w in re.split(r"[\s,:–—-]+", topic.strip()) if len(w) > 3]
    return words[0].capitalize() if words else "этого продукта"


async def complete(cfg, system: str, user: str) -> str:
    """Один запрос к модели. Возвращает текст или бросает RuntimeError с пояснением."""
    if not cfg.can_write:
        raise RuntimeError("LLM_API_KEY не задан")

    timeout = aiohttp.ClientTimeout(total=180)
    async with aiohttp.ClientSession(timeout=timeout) as s:
        if cfg.llm_format == "anthropic":
            payload = {
                "model": cfg.llm_model,
                "max_tokens": cfg.llm_max_tokens,
                "temperature": cfg.llm_temperature,
                "system": system,
                "messages": [{"role": "user", "content": user}],
            }
            headers = {"x-api-key": cfg.llm_key, "anthropic-version": "2023-06-01"}
            url = cfg.llm_base.rstrip("/") + "/messages"
        else:
            payload = {
                "model": cfg.llm_model,
                "max_tokens": cfg.llm_max_tokens,
                "temperature": cfg.llm_temperature,
                "messages": [{"role": "system", "content": system},
                             {"role": "user", "content": user}],
            }
            headers = {"Authorization": f"Bearer {cfg.llm_key}"}
            url = cfg.llm_base.rstrip("/") + "/chat/completions"

        async with s.post(url, json=payload, headers=headers) as r:
            raw = await r.text()
            if r.status >= 400:
                raise RuntimeError(f"модель ответила {r.status}: {raw[:400]}")
            data = json.loads(raw)
            if cfg.llm_format == "anthropic":
                return "".join(b.get("text", "") for b in data.get("content", []))
            return data["choices"][0]["message"]["content"]


def clean(text: str) -> str:
    """Снимает обёртку ``` и склеивает лишние пустые строки."""
    t = text.strip()
    m = re.match(r"^```[a-zA-Z]*\s*\n(.*)\n```\s*$", t, re.S)
    if m:
        t = m.group(1).strip()
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t


async def draft(cfg, repo, kind: str, topic: str, tone: str = "") -> tuple[str, str]:
    """Возвращает (текст, источник): 'llm' или 'local'."""
    template = FORMATS.get(kind, FORMATS["post"])
    user = template.format(topic=topic.strip().rstrip('.'), main_product=main_product(topic))
    if tone:
        user += f"\n\nДополнительно от автора: {tone}"

    if cfg.can_write:
        passport = repo.channel_passport()
        system = SYSTEM_CORE + ("\n\nПаспорт канала (источник тона и рубрик):\n" + passport if passport else "")
        text = clean(await complete(cfg, system, user))
        if text:
            return text, "llm"

    return local_draft(kind, topic), "local"


